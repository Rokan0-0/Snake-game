import React from 'react';
import { Disc3 } from 'lucide-react';
import { TrackConfig, TRACKS } from '../types/game';

interface TrackListProps {
  activeTrackIndex: number;
  isMusicPlaying: boolean;
  onSelectTrack: (index: number) => void;
}

export const TrackList: React.FC<TrackListProps> = ({
  activeTrackIndex,
  isMusicPlaying,
  onSelectTrack,
}) => {
  return (
    <section
      aria-label="Track selector"
      className="cyber-glass rounded-2xl border border-white/10 p-5 flex flex-col gap-4"
    >
      <div className="flex items-center justify-between border-b border-white/8 pb-3">
        <h2 className="font-display text-sm font-bold tracking-wider text-white">
          Soundtrack
        </h2>
        <span className="font-mono text-xs text-slate-400 tabular-nums">
          3 Loops
        </span>
      </div>

      <div className="flex flex-col gap-2.5">
        {TRACKS.map((track: TrackConfig, idx: number) => {
          const isActive = idx === activeTrackIndex;
          return (
            <button
              key={track.id}
              type="button"
              onClick={() => onSelectTrack(idx)}
              className={`group text-left rounded-xl p-3.5 border transition-all duration-150 cursor-pointer focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-cyan-400 ${
                isActive
                  ? 'bg-white/[0.08] border-white/25'
                  : 'bg-white/[0.02] border-white/5 hover:bg-white/[0.05] hover:border-white/15'
              }`}
              style={
                isActive
                  ? {
                      boxShadow: `0 0 22px -6px ${track.theme.primary}55`,
                    }
                  : undefined
              }
            >
              <div className="flex items-start justify-between gap-2">
                <div className="min-w-0">
                  <div className="flex items-center gap-2">
                    <Disc3
                      className={`w-4 h-4 shrink-0 transition-transform ${
                        isActive && isMusicPlaying ? 'animate-spin' : ''
                      }`}
                      style={{
                        color: isActive ? track.theme.primary : '#64748b',
                        animationDuration: '3.2s',
                      }}
                    />
                    <span className="font-display text-sm font-bold text-white truncate">
                      {track.title}
                    </span>
                  </div>
                  <p className="text-xs text-slate-400 mt-1 truncate">
                    Generated by {track.generatedBy}
                  </p>
                </div>

                <span
                  className="font-mono text-xs font-semibold tabular-nums shrink-0"
                  style={{ color: isActive ? track.theme.primary : '#94a3b8' }}
                >
                  {track.bpm} BPM
                </span>
              </div>

              <div className="mt-2.5 flex items-center gap-2 text-xs text-slate-400">
                <span className="text-slate-300 font-medium">{track.genre}</span>
                <span aria-hidden="true">·</span>
                <span className="truncate">{track.theme.foodShape} nodes</span>
              </div>
            </button>
          );
        })}
      </div>

      <p className="text-xs text-slate-400 leading-relaxed pt-1 border-t border-white/8">
        Switching tracks shifts the BPM speed, visual theme, and live audio spectrum in real time.
      </p>
    </section>
  );
};
